/**
 * App language. English is the source text everywhere; [tr] swaps in the Indonesian line when
 * the user picks it. Words like Agent, Session, Prompt, Provider, Model, Workspace and Skills
 * stay English on purpose. Reading [lang] inside composition recomposes on change.
 */
enum class AppLanguage(val code: String, val label: String) {
    ENGLISH("en", "English"),
    INDONESIAN("id", "Bahasa Indonesia");

    companion object {
        fun parse(s: String?): AppLanguage = entries.firstOrNull { it.code == s?.trim()?.lowercase() } ?: ENGLISH
    }
}

object I18n {
    var lang by mutableStateOf(AppLanguage.ENGLISH)
}

/** [en] in the current language. */
fun tr(en: String): String =
    if (I18n.lang == AppLanguage.INDONESIAN) ID[en] ?: en else en

/** Like [tr] for text with {0}, {1}… slots. */
fun trf(en: String, vararg args: Any?): String {
    var out = tr(en)
    args.forEachIndexed { i, a -> out = out.replace("{$i}", a?.toString() ?: "") }
    return out
}

